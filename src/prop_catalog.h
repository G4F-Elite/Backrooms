//   2. add its row to PROP_CATALOG (same order as the enum),
//   3. build its mesh in one of the props_*.h files and hook it up in
//      props_library.h.
// tests/prop_library_tests.cpp checks that mesh, footprint and row agree.
// ============================================================================

